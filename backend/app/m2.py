"""Module 2: redraw every figure as a clean, exact copy of the printed one.

Diagrams, charts and maps that M1 could turn into a structure are redrawn as clean SVG (no model, no cost).
Everything else is generated by an image model. To get an exact replica, not a loose re-imagining:
  1. a strong vision model describes the figure again, element by element, with positions and exact labels;
  2. the image model is given the original picture itself plus that description, and asked only to clean it up.
Photos or drawings of real people (Gandhiji, scientists, leaders) are never generated: the printed picture is
kept and only cleaned up (colour, contrast, sharpness, size), with no AI.
The original is always kept; the reviewer chooses which one students see.
"""
