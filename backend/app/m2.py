def replica(original: bytes, prompt: str, w: int, h: int, cfg: dict) -> bytes:
    """Image model given the original picture as the reference, for an exact clean copy."""
    import requests
    name = cfg["provider"]; p = cfg["providers"][name]; t = int(cfg.get("timeout_s", 180))
    base = p["base_url"].rstrip("/"); src = _png(original, 1536)
    if name == "openai" and not p["model"].startswith("dall-e"):
        data = {"model": p["model"], "prompt": prompt, "n": "1", "size": f"{w}x{h}", "input_fidelity": "high"}
        if p.get("quality"):
            data["quality"] = p["quality"]
        def post(d):
            return requests.post(base + "/images/edits", data=d, files={"image": ("figure.png", src, "image/png")}, timeout=t,
                                 headers={"Authorization": f"Bearer {p[SECRET]}"})
        r = post(data)
        if r.status_code == 400 and "input_fidelity" in r.text:
            data.pop("input_fidelity"); r = post(data)
        _raise(r, "OpenAI")
        item = r.json()["data"][0]
        return base64.b64decode(item["b64_json"]) if item.get("b64_json") else requests.get(item["url"], timeout=t).content
    if name == "gemini" and p["model"].startswith("gemini"):
        r = requests.post(f"{base}/models/{p['model']}:generateContent", headers={"x-goog-api-key": p[SECRET]}, timeout=t, json={
            "contents": [{"parts": [{"inlineData": {"mimeType": "image/png", "data": base64.b64encode(src).decode()}}, {"text": prompt}]}],
            "generationConfig": {"responseModalities": ["IMAGE"], "imageConfig": {"aspectRatio": _aspect(w, h)}}})
        _raise(r, "Gemini")
        for part in r.json()["candidates"][0]["content"]["parts"]:
            if part.get("inlineData"):
                return base64.b64decode(part["inlineData"]["data"])
        raise RuntimeError("Gemini answered without an image")
    if name == "local":  # img2img keeps the original's layout; low denoising = close copy
        body = {"prompt": prompt, "init_images": [base64.b64encode(src).decode()], "denoising_strength": float(p.get("denoise") or 0.35),
                "width": min(w, 1024), "height": min(h, 1024), "steps": int(p.get("steps") or 25)}
        hdr = {"Authorization": f"Bearer {p[SECRET]}"} if p.get(SECRET) else {}
        r = requests.post(base + "/sdapi/v1/img2img", json=body, headers=hdr, timeout=t)
        _raise(r, "Local image model")
        return base64.b64decode(r.json()["images"][0].split(",", 1)[-1])
    return generate(prompt, w, h, cfg)   # models with no picture input (Imagen, DALL-E) draw from the words alone


# ---------- one figure ----------
def _stem(block) -> str:
    return PurePosixPath((block.get("m2") or {}).get("original") or block["image"]).stem


def redo_figure(book, block, specs: dict, cfg: dict, report: dict, allow_svg=True) -> dict:
    """Make a new picture for one figure block. Returns the m2 record (also stored on the block)."""
    store = C._store()
    original = (block.get("m2") or {}).get("original") or block["image"]
    stem = _stem(block)
    d = block.get("desc") or {}
    kind = (d.get("type") or "").lower()
    rec = {"original": original, "choice": "pending", "at": datetime.utcnow().isoformat(timespec="seconds"),
           "kind": kind, "status": "skipped", "method": "", "image": "", "error": "", "prompt": ""}
    spec = (specs.get(stem) or {}).get("spec") if specs else None
    n = int((block.get("m2") or {}).get("version", 0)) + 1
    rec["version"] = n
    try:
        if allow_svg and cfg.get("svg_redraw", True) and spec and kind in cfg.get("svg_kinds", []):
            from eduverse_book2docx import svgdraw  # noqa: imported through app.m1's path
            if svgdraw.is_regenerable(spec):
                svg = svgdraw.build(spec, block.get("width") or 600, block.get("height") or 400)
                if svg:
                    key = f"images/m2/{stem}_v{n}.svg"
                    store.put(f"{book.content_key}/{key}", svg.encode("utf-8"))
                    rec.update(status="generated", method="svg", image=key)
                    report["svg"] = report.get("svg", 0) + 1
                    return rec
        if kind in ("decorative", "text_banner"):
            rec["error"] = "Decoration or text banner: kept as printed"
            return rec
        try:
            src = store.get(f"{book.content_key}/{original}")
        except Exception:
            src = None
        # A careful second description first: it decides whether this is a real person, and guides the copy.
        if src and cfg.get("deep_describe", True) and d.get("quality") != "deep" and ready(cfg)[0] and cfg["provider"] in ("openai", "gemini"):
            try:
                block["desc"] = d = merge_desc(d, deep_describe(src, cfg))
                kind = (d.get("type") or kind).lower(); rec["kind"] = kind
                report["described"] = report.get("described", 0) + 1
            except Exception as e:
                rec["note"] = f"Could not describe again: {str(e)[:160]}"
        if cfg.get("people", "keep") == "keep" and is_person(block):
            if not src:
                rec["error"] = "Real person: kept as printed"
                return rec
            key = f"images/m2/{stem}_v{n}_clean.png"
            store.put(f"{book.content_key}/{key}", enhance(src, photo=kind != "diagram"))
            rec.update(status="generated", method="enhance", image=key,
                       note="A real person is never generated. This is the printed picture, cleaned up: colour, contrast, sharpness and size.")
            report["people"] = report.get("people", 0) + 1
            return rec
        if kind not in cfg.get("generate_kinds", []):
            rec["error"] = f"{kind or 'This kind of figure'} is not set to be generated in M2 settings"
            return _clean_copy(book, store, src, stem, n, kind, rec, report)
        if not d.get("summary") and not (src and cfg.get("replica", True)):
            rec["error"] = "No description to draw from"
            return _clean_copy(book, store, src, stem, n, kind, rec, report)
        ok, why = ready(cfg)
        if not ok:
            rec["error"] = why
            return _clean_copy(book, store, src, stem, n, kind, rec, report)
        if report.get("calls", 0) >= int(cfg.get("max_images_per_book", 100)):
            rec["error"] = f"Spend limit reached ({cfg.get('max_images_per_book')} images for this book)"
            return rec
        w, h = _size(block, cfg)
        report["calls"] = report.get("calls", 0) + 1
        if src and cfg.get("replica", True):
            rec["prompt"] = (REPLICA + "\n\nDescription to check your copy against:\n" + prompt_for(block, book, {**cfg, "style_prompt": ""}))[:3800]
            png = _png(replica(src, rec["prompt"], w, h, cfg)); rec["mode"] = "replica"
        else:
            rec["prompt"] = prompt_for(block, book, cfg)
            png = _png(generate(rec["prompt"], w, h, cfg)); rec["mode"] = "from words"
        png = _png(fit_aspect(png, block.get("width") or 0, block.get("height") or 0), 1536)
        key = f"images/m2/{stem}_v{n}.png"
        store.put(f"{book.content_key}/{key}", png)
        rec.update(status="generated", method=cfg["provider"], model=cfg["providers"][cfg["provider"]].get("model", ""), image=key)
        want = [t for t in (d.get("text_in_figure") or []) if str(t).strip()]
        if want and cfg["provider"] in ("openai", "gemini") and cfg.get("check_labels", True):
            try:   # image models misspell or drop labels; read the new picture back and tell the reviewer
                got = deep_describe(png, cfg).get("text_in_figure") or []
                rec["label_check"] = label_check(want, got)
                if rec["label_check"]["missing"]:
                    rec["note"] = "Check the labels: " + ", ".join(rec["label_check"]["missing"][:8]) + " not found in the new picture."
            except Exception as e:
                rec["label_check"] = {"error": str(e)[:160]}
        report["generated"] = report.get("generated", 0) + 1
    except Exception as e:
        rec.update(status="failed", error=str(e)[:400])
        report["failed"] = report.get("failed", 0) + 1
    return rec


def _norm_label(t) -> str:
    return re.sub(r"[^0-9a-z]+", "", str(t).lower())


def label_check(want: list, got: list) -> dict:
    """Printed labels that the new picture does not carry, spelled exactly (case and spaces ignored)."""
    have = {_norm_label(g) for g in got}
    missing = [w for w in want if _norm_label(w) and _norm_label(w) not in have]
    return {"expected": len(want), "missing": missing}


def fit_aspect(png: bytes, w0: float, h0: float) -> bytes:
    """An image model only draws a few fixed shapes. Pad the new picture with its own
    background to the printed figure's shape, so the page does not jump and nothing is stretched."""
    if not w0 or not h0:
        return png
    from PIL import Image
    im = Image.open(io.BytesIO(png)).convert("RGB")
    want = w0 / h0; have = im.width / im.height
    if abs(have - want) / want < 0.04:
        return png
    W, H = (round(im.height * want), im.height) if want > have else (im.width, round(im.width / want))
    corners = [im.getpixel(p) for p in ((0, 0), (im.width - 1, 0), (0, im.height - 1), (im.width - 1, im.height - 1))]
    bg = tuple(sorted(c[i] for c in corners)[1] for i in range(3))
    out = Image.new("RGB", (W, H), bg); out.paste(im, ((W - im.width) // 2, (H - im.height) // 2))
    buf = io.BytesIO(); out.save(buf, "PNG", optimize=True)
    return buf.getvalue()


def _clean_copy(book, store, src, stem, n, kind, rec, report) -> dict:
    """When a figure is not redrawn, still offer the reviewer the no-AI clean up, but only
    when it visibly improves the picture (flat artwork is left as printed)."""
    if not src:
        return rec
    try:
        from PIL import Image, ImageChops
        out = enhance(src, photo=kind not in ("diagram", "chart", "map"))
        a = Image.open(io.BytesIO(src)).convert("RGB"); b = Image.open(io.BytesIO(out)).convert("RGB").resize(a.size)
        diff = ImageChops.difference(a, b).convert("L")
        changed = sum(diff.histogram()[24:]) / max(1, a.width * a.height)
        if changed < 0.05 and max(a.size) >= 900:
            return rec   # nothing a reader would notice
        key = f"images/m2/{stem}_v{n}_clean.png"
        store.put(f"{book.content_key}/{key}", out)
        rec.update(status="generated", method="enhance", image=key,
                   note=((rec["error"] + ". ") if rec.get("error") else "") + "Offered instead: the printed picture cleaned up (colour, contrast, sharpness, size), nothing redrawn.")
        rec["error"] = ""
        report["cleaned"] = report.get("cleaned", 0) + 1
    except Exception as e:
        rec["note"] = f"Clean up failed: {str(e)[:120]}"
    return rec


def apply(block, rec):
    """Store the record; until the reviewer chooses, students keep seeing the original."""
    block["m2"] = rec
    block["image"] = rec["original"]


def figures(data):
    for ch in data["chapters"]:
        for b, _ in C.walk(ch["blocks"]):
            if b["type"] == "figure":
                yield b


def run_book(db, book, progress=lambda done, total: None) -> dict:
    cfg = with_env(settings_of(db))
    if not cfg.get("enabled"):
        return {"skipped": "M2 is switched off"}
    data = C.load(book)
    specs = C.load_extra(book, "m1_specs.json") or {}
    report = C.load_extra(book, "m2_report.json") or {}
    figs = list(figures(data))
    for i, b in enumerate(figs, 1):
        if (b.get("m2") or {}).get("status") != "generated":
            apply(b, redo_figure(book, b, specs, cfg, report))
        progress(i, len(figs))
        if i % 5 == 0:
            C.save(book, data)
    C.save(book, data)
    counts = {"figures": len(figs)}
    for b in figs:
        s = (b.get("m2") or {}).get("status", "skipped")
        counts[s] = counts.get(s, 0) + 1
    report.update(counts=counts, provider=cfg["provider"], finished=datetime.utcnow().isoformat(timespec="seconds"))
    C._store().put(f"{book.content_key}/m2_report.json", json.dumps(report).encode())
    return report


def pending_on_page(data, page: int) -> list:
    """Generated pictures on this page the reviewer has not chosen for yet."""
    out = []
    for b in figures(data):
        if b.get("page") == page and (b.get("m2") or {}).get("status") == "generated" and b["m2"].get("choice") == "pending":
            out.append(("Figure " + b["number"]) if b.get("number") else (b.get("caption") or "a figure"))
    return out
