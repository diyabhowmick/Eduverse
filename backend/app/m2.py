# ---------- settings ----------
def settings_of(db) -> dict:
    s = db.get(Setting, "m2")
    val = copy.deepcopy(M2)
    if s and s.value:
        for k, v in s.value.items():
            if k == "providers":
                for n, p in (v or {}).items():
                    val["providers"].setdefault(n, {}).update(p or {})
            else:
                val[k] = v
    return val


ENV_KEYS = {"openai": "OPENAI_API_KEY", "gemini": "GEMINI_API_KEY"}  # provider -> server environment variable


def env_keys() -> list:
    """Providers that have a key in the server environment (Railway variables)."""
    return [n for n, env in ENV_KEYS.items() if os.getenv(env)]


def with_env(cfg: dict) -> dict:
    """Settings to draw with: a key typed in Settings wins, otherwise the server's environment variable.
    Used only at run time, never for what is saved or shown, so an environment key never lands in the database."""
    cfg = copy.deepcopy(cfg)
    for name, env in ENV_KEYS.items():
        p = cfg["providers"].setdefault(name, {})
        if not p.get(SECRET) and os.getenv(env):
            p[SECRET] = os.getenv(env)
    return cfg


def masked(v: dict) -> dict:
    v = copy.deepcopy(v)
    for p in (v.get("providers") or {}).values():
        if p.get(SECRET):
            p[SECRET] = "saved"
    return v


def ready(cfg: dict) -> tuple[bool, str]:
    p = cfg["providers"].get(cfg["provider"], {})
    if cfg["provider"] in ("openai", "gemini") and not p.get(SECRET):
        return False, f"No {cfg['provider'].title()} API key in M2 settings"
    if not p.get("base_url"):
        return False, "No address for the image model"
    return True, ""


# ---------- prompt ----------
def prompt_for(block: dict, book, cfg: dict) -> str:
    d = block.get("desc") or {}
    kind = d.get("type") or "illustration"
    lines = [cfg.get("style_prompt", "").strip(), ""]
    who = " ".join(x for x in (f"Class {book.grade}" if book.grade else "", book.subject or "", "textbook") if x)
    lines.append(f"Draw this {kind} for a {who}.")
    if block.get("number") or block.get("caption"):
        lines.append(f"Caption: {('Figure ' + block['number'] + '. ') if block.get('number') else ''}{block.get('caption') or ''}".strip())
    if d.get("replica_brief"):
        lines.append("Exact layout: " + d["replica_brief"].strip())
    elif d.get("summary"):
        lines.append("What it shows: " + d["summary"].strip())
    if d.get("elements"):
        lines.append("Elements, each in its place: " + " | ".join(
            ", ".join(str(e.get(k)) for k in ("name", "position", "size", "shape", "colour", "line_style", "text") if e.get(k)) for e in d["elements"][:30]))
    if d.get("parts"):
        lines.append("Parts that must appear: " + "; ".join(d["parts"]))
    if d.get("relations"):
        lines.append("How the parts relate: " + " ".join(d["relations"]))
    if d.get("data"):
        lines.append("Values shown: " + "; ".join(d["data"]))
    if d.get("text_in_figure"):
        lines.append("Printed labels to include, spelled exactly: " + "; ".join(f'"{t}"' for t in d["text_in_figure"]))
        lines.append("Do not add any other text.")
    else:
        lines.append("Do not add any text or labels.")
    p = "\n".join(l for l in lines if l is not None).strip()
    limit = 1800 if cfg["provider"] == "gemini" else 3800
    return p[:limit]


def _size(block, cfg) -> tuple[int, int]:
    if cfg.get("size", "auto") != "auto":
        w, h = (int(x) for x in cfg["size"].lower().split("x"))
        return w, h
    w, h = block.get("width") or 1, block.get("height") or 1
    r = w / h
    return (1536, 1024) if r > 1.25 else (1024, 1536) if r < 0.8 else (1024, 1024)


def _aspect(w, h) -> str:
    r = w / h
    return min(("1:1", 1), ("4:3", 4 / 3), ("3:4", 3 / 4), ("16:9", 16 / 9), ("9:16", 9 / 16), key=lambda a: abs(a[1] - r))[0]


# ---------- providers ----------
def generate(prompt: str, w: int, h: int, cfg: dict) -> bytes:
    import requests
    name = cfg["provider"]; p = cfg["providers"][name]; t = int(cfg.get("timeout_s", 180))
    base = p["base_url"].rstrip("/")
    if name == "openai":
        body = {"model": p["model"], "prompt": prompt, "n": 1, "size": f"{w}x{h}"}
        if p["model"].startswith("dall-e"):
            body["response_format"] = "b64_json"
            if p["model"] == "dall-e-3":
                body["size"] = "1792x1024" if w > h else "1024x1792" if h > w else "1024x1024"
            else:
                body["size"] = "1024x1024"
        elif p.get("quality"):
            body["quality"] = p["quality"]
        r = requests.post(base + "/images/generations", json=body, timeout=t,
                          headers={"Authorization": f"Bearer {p[SECRET]}"})
        _raise(r, "OpenAI")
        item = r.json()["data"][0]
        if item.get("b64_json"):
            return base64.b64decode(item["b64_json"])
        return requests.get(item["url"], timeout=t).content
    if name == "gemini":
        hdr = {"x-goog-api-key": p[SECRET]}
        if p["model"].startswith("gemini"):
            r = requests.post(f"{base}/models/{p['model']}:generateContent", headers=hdr, timeout=t, json={
                "contents": [{"parts": [{"text": prompt}]}],
                "generationConfig": {"responseModalities": ["IMAGE"], "imageConfig": {"aspectRatio": _aspect(w, h)}}})
            _raise(r, "Gemini")
            for part in r.json()["candidates"][0]["content"]["parts"]:
                if part.get("inlineData"):
                    return base64.b64decode(part["inlineData"]["data"])
            raise RuntimeError("Gemini answered without an image")
        r = requests.post(f"{base}/models/{p['model']}:predict", headers=hdr, timeout=t, json={
            "instances": [{"prompt": prompt}], "parameters": {"sampleCount": 1, "aspectRatio": _aspect(w, h)}})
        _raise(r, "Gemini")
        preds = r.json().get("predictions") or []
        if not preds:
            raise RuntimeError("Gemini returned no image (the prompt may have been filtered)")
        return base64.b64decode(preds[0]["bytesBase64Encoded"])
    if name == "local":  # Stable Diffusion WebUI / Forge compatible txt2img API
        body = {"prompt": prompt, "width": min(w, 1024), "height": min(h, 1024), "steps": int(p.get("steps") or 25)}
        if p.get("model"):
            body["override_settings"] = {"sd_model_checkpoint": p["model"]}
        hdr = {"Authorization": f"Bearer {p[SECRET]}"} if p.get(SECRET) else {}
        r = requests.post(base + "/sdapi/v1/txt2img", json=body, headers=hdr, timeout=t)
        _raise(r, "Local image model")
        return base64.b64decode(r.json()["images"][0].split(",", 1)[-1])
    raise RuntimeError(f"Unknown image provider {name}")


def _raise(r, who):
    if r.status_code >= 400:
        try:
            msg = r.json().get("error", {})
            msg = msg.get("message") if isinstance(msg, dict) else msg
        except Exception:
            msg = r.text
        raise RuntimeError(f"{who} {r.status_code}: {str(msg)[:240]}")


def _png(data: bytes, cap: int = 1000) -> bytes:
    from PIL import Image
    im = Image.open(io.BytesIO(data))
    im = im.convert("RGBA") if im.mode in ("P", "LA", "RGBA") else im.convert("RGB")
    if max(im.size) > cap:
        im.thumbnail((cap, cap))
    buf = io.BytesIO(); im.save(buf, "PNG", optimize=True)
    return buf.getvalue()



# ---------- real people ----------
_PEOPLE = re.compile(r"\b(portrait|photograph of (?:a |the )?(?:man|woman|leader|scientist)|mahatma|gandhi(?:ji)?|nehru|ambedkar|tagore|subhas|netaji|"
                     r"sardar patel|bhagat singh|vivekananda|kalam|c\.?\s?v\.? raman|ramanujan|bharathiyar|bharathi|periyar|kamaraj|thiruvalluvar|"
                     r"einstein|newton|darwin|galileo|curie|edison|faraday|freedom fighter|prime minister|president of|emperor|king |queen |"
                     r"scientist|poet|leader|saint|reformer)\b", re.I)


def is_person(block) -> bool:
    """Photos or drawings of real, identifiable people are never generated."""
    d = block.get("desc") or {}
    if d.get("real_people") is True:
        return True
    if d.get("real_people") is False:
        return False
    text = " ".join(str(x) for x in (block.get("caption"), d.get("summary"), d.get("replica_brief"), " ".join(d.get("parts") or [])) if x)
    return bool(_PEOPLE.search(text))


def _few_colours(im) -> bool:
    """Most of the picture is a handful of colours: printed flat artwork with anti-aliased edges."""
    q = im.quantize(16); counts = sorted((c for c, _ in q.getcolors() or []), reverse=True)
    return sum(counts[:8]) >= 0.97 * sum(counts) if counts else False


def enhance(data: bytes, photo: bool = True) -> bytes:
    """Clean up a printed picture without AI: even out the colour cast and yellowing, lift contrast,
    remove speckle, sharpen, and enlarge small scans. Nothing is added or redrawn."""
    from PIL import Image, ImageFilter, ImageStat
    im = Image.open(io.BytesIO(data)).convert("RGB")
    # Flat artwork (a few solid colours) is left exactly as printed: stretching
    # each colour channel on its own turned brown soil red and green seeds black.
    small = im.copy(); small.thumbnail((200, 200))
    flat = len(small.getcolors(200 * 200) or []) <= 96 or _few_colours(small)
    if not flat:
        # yellowed paper: only a warm cast on the paper white is corrected, and the
        # same scale is used for the whole picture so hues keep their colour
        grey = im.convert("L"); hist = grey.histogram(); total = sum(hist); acc = 0; cut = 255
        for i in range(255, -1, -1):
            acc += hist[i]
            if acc >= total * 0.02: cut = i; break
        mask = grey.point(lambda v: 255 if v >= cut else 0)
        r, g, b_ = (ImageStat.Stat(c, mask).mean[0] for c in im.split())
        if b_ < min(r, g) - 6 and min(r, g, b_) > 120:
            im = Image.merge("RGB", [c.point(lambda v, k=255 / max(1.0, m): min(255, round(v * k)))
                                     for c, m in zip(im.split(), (r, g, b_))])
        if photo:
            im = im.filter(ImageFilter.MedianFilter(3))
        # contrast on brightness only (same map on every channel)
        hist = im.convert("L").histogram(); total = sum(hist); acc = 0; lo = hi = None
        for i, n in enumerate(hist):
            acc += n
            if lo is None and acc >= total * 0.005: lo = i
            if acc >= total * 0.995: hi = i; break
        lo, hi = lo or 0, hi or 255
        if hi - lo < 230 and hi > lo:
            k = 255 / (hi - lo)
            im = im.point(lambda v: max(0, min(255, round((v - lo) * k))))
    long = max(im.size)
    if long < 900:
        f = 900 / long
        im = im.resize((round(im.width * f), round(im.height * f)), Image.LANCZOS)
    im = im.filter(ImageFilter.UnsharpMask(radius=2, percent=110 if photo else 160, threshold=3))
    buf = io.BytesIO(); im.save(buf, "PNG", optimize=True)
    return buf.getvalue()


