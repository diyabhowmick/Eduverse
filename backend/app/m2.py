"""Module 2: redraw every figure from its description instead of reusing the scanned picture.

Diagrams, charts and maps that M1 could turn into a structure are redrawn as clean SVG (no model, no cost).
Everything else is generated by an image model from the description, the named parts, the printed labels
and the caption. The original is always kept; the reviewer chooses which one students see.
"""
import base64, copy, io, json, time
from datetime import datetime
from pathlib import PurePosixPath
from . import content as C
from . import m1  # noqa: F401  puts M1 (svgdraw) on the path
from .defaults import M2
from .models import Setting

SECRET = "api_key"


# ---------- settings ----------
def settings_of(db) -> dict:
    s = db.get(Setting, "m2")
    val = copy.deepcopy(M2)
    if s and s.value:
        for k, v in s.value.items():
            if k == "providers":
                for n, p in (v or {}).items():
                    val["providers"].setdefault(n, {}).update(p or {})
            else:
                val[k] = v
    return val


def masked(v: dict) -> dict:
    v = copy.deepcopy(v)
    for p in (v.get("providers") or {}).values():
        if p.get(SECRET):
            p[SECRET] = "saved"
    return v


def ready(cfg: dict) -> tuple[bool, str]:
    p = cfg["providers"].get(cfg["provider"], {})
    if cfg["provider"] in ("openai", "gemini") and not p.get(SECRET):
        return False, f"No {cfg['provider'].title()} API key in M2 settings"
    if not p.get("base_url"):
        return False, "No address for the image model"
    return True, ""


# ---------- prompt ----------
def prompt_for(block: dict, book, cfg: dict) -> str:
    d = block.get("desc") or {}
    kind = d.get("type") or "illustration"
    lines = [cfg.get("style_prompt", "").strip(), ""]
    who = " ".join(x for x in (f"Class {book.grade}" if book.grade else "", book.subject or "", "textbook") if x)
    lines.append(f"Draw this {kind} for a {who}.")
    if block.get("number") or block.get("caption"):
        lines.append(f"Caption: {('Figure ' + block['number'] + '. ') if block.get('number') else ''}{block.get('caption') or ''}".strip())
    if d.get("summary"):
        lines.append("What it shows: " + d["summary"].strip())
    if d.get("parts"):
        lines.append("Parts that must appear: " + "; ".join(d["parts"]))
    if d.get("relations"):
        lines.append("How the parts relate: " + " ".join(d["relations"]))
    if d.get("data"):
        lines.append("Values shown: " + "; ".join(d["data"]))
    if d.get("text_in_figure"):
        lines.append("Printed labels to include, spelled exactly: " + "; ".join(f'"{t}"' for t in d["text_in_figure"]))
        lines.append("Do not add any other text.")
    else:
        lines.append("Do not add any text or labels.")
    p = "\n".join(l for l in lines if l is not None).strip()
    limit = 1800 if cfg["provider"] == "gemini" else 3800
    return p[:limit]


def _size(block, cfg) -> tuple[int, int]:
    if cfg.get("size", "auto") != "auto":
        w, h = (int(x) for x in cfg["size"].lower().split("x"))
        return w, h
    w, h = block.get("width") or 1, block.get("height") or 1
    r = w / h
    return (1536, 1024) if r > 1.25 else (1024, 1536) if r < 0.8 else (1024, 1024)


def _aspect(w, h) -> str:
    r = w / h
    return min(("1:1", 1), ("4:3", 4 / 3), ("3:4", 3 / 4), ("16:9", 16 / 9), ("9:16", 9 / 16), key=lambda a: abs(a[1] - r))[0]


# ---------- providers ----------
def generate(prompt: str, w: int, h: int, cfg: dict) -> bytes:
    import requests
    name = cfg["provider"]; p = cfg["providers"][name]; t = int(cfg.get("timeout_s", 180))
    base = p["base_url"].rstrip("/")
    if name == "openai":
        body = {"model": p["model"], "prompt": prompt, "n": 1, "size": f"{w}x{h}"}
        if p["model"].startswith("dall-e"):
            body["response_format"] = "b64_json"
            if p["model"] == "dall-e-3":
                body["size"] = "1792x1024" if w > h else "1024x1792" if h > w else "1024x1024"
            else:
                body["size"] = "1024x1024"
        elif p.get("quality"):
            body["quality"] = p["quality"]
        r = requests.post(base + "/images/generations", json=body, timeout=t,
                          headers={"Authorization": f"Bearer {p[SECRET]}"})
        _raise(r, "OpenAI")
        item = r.json()["data"][0]
        if item.get("b64_json"):
            return base64.b64decode(item["b64_json"])
        return requests.get(item["url"], timeout=t).content
    if name == "gemini":
        hdr = {"x-goog-api-key": p[SECRET]}
        if p["model"].startswith("gemini"):
            r = requests.post(f"{base}/models/{p['model']}:generateContent", headers=hdr, timeout=t, json={
                "contents": [{"parts": [{"text": prompt}]}],
                "generationConfig": {"responseModalities": ["IMAGE"], "imageConfig": {"aspectRatio": _aspect(w, h)}}})
            _raise(r, "Gemini")
            for part in r.json()["candidates"][0]["content"]["parts"]:
                if part.get("inlineData"):
                    return base64.b64decode(part["inlineData"]["data"])
            raise RuntimeError("Gemini answered without an image")
        r = requests.post(f"{base}/models/{p['model']}:predict", headers=hdr, timeout=t, json={
            "instances": [{"prompt": prompt}], "parameters": {"sampleCount": 1, "aspectRatio": _aspect(w, h)}})
        _raise(r, "Gemini")
        preds = r.json().get("predictions") or []
        if not preds:
            raise RuntimeError("Gemini returned no image (the prompt may have been filtered)")
        return base64.b64decode(preds[0]["bytesBase64Encoded"])
    if name == "local":  # Stable Diffusion WebUI / Forge compatible txt2img API
        body = {"prompt": prompt, "width": min(w, 1024), "height": min(h, 1024), "steps": int(p.get("steps") or 25)}
        if p.get("model"):
            body["override_settings"] = {"sd_model_checkpoint": p["model"]}
        hdr = {"Authorization": f"Bearer {p[SECRET]}"} if p.get(SECRET) else {}
        r = requests.post(base + "/sdapi/v1/txt2img", json=body, headers=hdr, timeout=t)
        _raise(r, "Local image model")
        return base64.b64decode(r.json()["images"][0].split(",", 1)[-1])
    raise RuntimeError(f"Unknown image provider {name}")


def _raise(r, who):
    if r.status_code >= 400:
        try:
            msg = r.json().get("error", {})
            msg = msg.get("message") if isinstance(msg, dict) else msg
        except Exception:
            msg = r.text
        raise RuntimeError(f"{who} {r.status_code}: {str(msg)[:240]}")


def _png(data: bytes, cap: int = 1000) -> bytes:
    from PIL import Image
    im = Image.open(io.BytesIO(data))
    im = im.convert("RGBA") if im.mode in ("P", "LA", "RGBA") else im.convert("RGB")
    if max(im.size) > cap:
        im.thumbnail((cap, cap))
    buf = io.BytesIO(); im.save(buf, "PNG", optimize=True)
    return buf.getvalue()


# ---------- one figure ----------
def _stem(block) -> str:
    return PurePosixPath((block.get("m2") or {}).get("original") or block["image"]).stem


def redo_figure(book, block, specs: dict, cfg: dict, report: dict, allow_svg=True) -> dict:
    """Make a new picture for one figure block. Returns the m2 record (also stored on the block)."""
    store = C._store()
    original = (block.get("m2") or {}).get("original") or block["image"]
    stem = _stem(block)
    d = block.get("desc") or {}
    kind = (d.get("type") or "").lower()
    rec = {"original": original, "choice": "pending", "at": datetime.utcnow().isoformat(timespec="seconds"),
           "kind": kind, "status": "skipped", "method": "", "image": "", "error": "", "prompt": ""}
    spec = (specs.get(stem) or {}).get("spec") if specs else None
    n = int((block.get("m2") or {}).get("version", 0)) + 1
    rec["version"] = n
    try:
        if allow_svg and cfg.get("svg_redraw", True) and spec and kind in cfg.get("svg_kinds", []):
            from eduverse_book2docx import svgdraw  # noqa: imported through app.m1's path
            if svgdraw.is_regenerable(spec):
                svg = svgdraw.build(spec, block.get("width") or 600, block.get("height") or 400)
                if svg:
                    key = f"images/m2/{stem}_v{n}.svg"
                    store.put(f"{book.content_key}/{key}", svg.encode("utf-8"))
                    rec.update(status="generated", method="svg", image=key)
                    report["svg"] = report.get("svg", 0) + 1
                    return rec
        if kind in ("decorative", "text_banner"):
            rec["error"] = "Decoration or text banner: kept as printed"
            return rec
        if kind not in cfg.get("generate_kinds", []):
            rec["error"] = f"{kind or 'This kind of figure'} is not set to be generated in M2 settings"
            return rec
        if not d.get("summary"):
            rec["error"] = "No description to draw from"
            return rec
        ok, why = ready(cfg)
        if not ok:
            rec["error"] = why
            return rec
        if report.get("calls", 0) >= int(cfg.get("max_images_per_book", 100)):
            rec["error"] = f"Spend limit reached ({cfg.get('max_images_per_book')} images for this book)"
            return rec
        rec["prompt"] = prompt_for(block, book, cfg)
        w, h = _size(block, cfg)
        report["calls"] = report.get("calls", 0) + 1
        png = _png(generate(rec["prompt"], w, h, cfg))
        key = f"images/m2/{stem}_v{n}.png"
        store.put(f"{book.content_key}/{key}", png)
        rec.update(status="generated", method=cfg["provider"], model=cfg["providers"][cfg["provider"]].get("model", ""), image=key)
        report["generated"] = report.get("generated", 0) + 1
    except Exception as e:
        rec.update(status="failed", error=str(e)[:400])
        report["failed"] = report.get("failed", 0) + 1
    return rec


def apply(block, rec):
    """Store the record; until the reviewer chooses, students keep seeing the original."""
    block["m2"] = rec
    block["image"] = rec["original"]


def figures(data):
    for ch in data["chapters"]:
        for b, _ in C.walk(ch["blocks"]):
            if b["type"] == "figure":
                yield b


def run_book(db, book, progress=lambda done, total: None) -> dict:
    cfg = settings_of(db)
    if not cfg.get("enabled"):
        return {"skipped": "M2 is switched off"}
    data = C.load(book)
    specs = C.load_extra(book, "m1_specs.json") or {}
    report = C.load_extra(book, "m2_report.json") or {}
    figs = list(figures(data))
    for i, b in enumerate(figs, 1):
        if (b.get("m2") or {}).get("status") != "generated":
            apply(b, redo_figure(book, b, specs, cfg, report))
        progress(i, len(figs))
        if i % 5 == 0:
            C.save(book, data)
    C.save(book, data)
    counts = {"figures": len(figs)}
    for b in figs:
        s = (b.get("m2") or {}).get("status", "skipped")
        counts[s] = counts.get(s, 0) + 1
    report.update(counts=counts, provider=cfg["provider"], finished=datetime.utcnow().isoformat(timespec="seconds"))
    C._store().put(f"{book.content_key}/m2_report.json", json.dumps(report).encode())
    return report


def pending_on_page(data, page: int) -> list:
    """Generated pictures on this page the reviewer has not chosen for yet."""
    out = []
    for b in figures(data):
        if b.get("page") == page and (b.get("m2") or {}).get("status") == "generated" and b["m2"].get("choice") == "pending":
            out.append(("Figure " + b["number"]) if b.get("number") else (b.get("caption") or "a figure"))
    return out
